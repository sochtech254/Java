package org.sochcode.Part2.ch30theStreamApi;

class NamePhoneEmail
{
    String name;
    String phonenum;
    String email;

    NamePhoneEmail(String n, String p, String e)
    {
        name = n;
        phonenum = p;
        email = e;
    }
}

class NamePhone
{
    String name;
    String phonenum;

    NamePhone(String n, String p)
    {
        name = n;
        phonenum = p;
    }
}

class NameEmail
{
    String name;
    String email;

    NameEmail(String n, String e)
    {
        name = n;
        email = e;
    }
}
