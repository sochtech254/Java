package org.sochcode.amigoscode;

public class LoopingAnArray
{
    public static void main(String[] args)
    {
        // Loops and Arrays
        String[] names = {
                "James",
                "Nadia",
                "Sophia",
                "Alex"
        };
        for (String name : names)
            System.out.println(name);
    }
}
