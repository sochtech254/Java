package org.sochcode.amigoscode;

public class Strings
{
    public static void main(String[] args)
    {
        // Strings
        String brand = "SochTech";
        System.out.println(brand.toLowerCase());

        // String Concatenation
        String code = "Code";
        String demon = "Demon";
        String anotherBrand = code + demon;
        System.out.println(anotherBrand.toUpperCase());
    }
}
