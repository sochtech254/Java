package org.sochcode.amigoscode;

public class ArithmeticOperators
{
    public static void main(String[] args)
    {
        int numberOne = 10;
        int numberTwo = 3;

        System.out.println(numberOne + numberTwo);
        System.out.println(numberOne - numberTwo);
        System.out.println(numberOne * numberTwo);
        System.out.println(numberOne / numberTwo);
        System.out.println(numberOne % numberTwo);
    }
}
