package org.sochtech.gettingtoknowthelanguage.javalanguagebasics;

public class ComparisonDemo {
    static void main() {
        int value1 = 1;
        int value2 = 2;

        if (value1 == value2)
            IO.println("value1 == value2");
        if (value1 != value2)
            IO.println("value1 != value2");
        if (value1 > value2)
            IO.println("value1 > value2");
        if (value1 < value2)
            IO.println("value1 < value2");
        if (value1 <= value2)
            IO.println("value1 <= value2");
    }
}
